CREATE TABLE IF NOT EXISTS usuarios_app (
  id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
  usuario VARCHAR(40) NOT NULL UNIQUE,
  nombre VARCHAR(160) NOT NULL,
  correo VARCHAR(254) NOT NULL UNIQUE,
  dpi CHAR(13) NULL UNIQUE,
  password_hash VARCHAR(255) NOT NULL,
  rol ENUM('aspirante','admin','superadmin') NOT NULL DEFAULT 'aspirante',
  activo BOOLEAN NOT NULL DEFAULT TRUE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
CREATE TABLE IF NOT EXISTS sesiones_app (
  token_hash CHAR(64) NOT NULL PRIMARY KEY,
  usuario_id BIGINT UNSIGNED NOT NULL,
  expira DATETIME(3) NOT NULL,
  FOREIGN KEY (usuario_id) REFERENCES usuarios_app(id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
CREATE TABLE IF NOT EXISTS estado_plataforma (
  id TINYINT UNSIGNED NOT NULL PRIMARY KEY,
  version BIGINT UNSIGNED NOT NULL DEFAULT 0,
  datos JSON NOT NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
CREATE TABLE IF NOT EXISTS documentos_plataforma (
  solicitud_id BIGINT UNSIGNED NOT NULL PRIMARY KEY,
  usuario_id BIGINT UNSIGNED NOT NULL,
  nombre VARCHAR(255) NOT NULL,
  tipo VARCHAR(80) NOT NULL,
  contenido MEDIUMBLOB NOT NULL,
  FOREIGN KEY (usuario_id) REFERENCES usuarios_app(id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
